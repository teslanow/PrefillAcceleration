class PyramidCache(Cache):
    def __init__(self, max_b, h, d, layer_num, dtype=torch.bfloat16, runtime_expand=False):
        super().__init__()
        self.key_cache: List[Optional[torch.Tensor]] = [None] * layer_num
        self.value_cache: List[Optional[torch.Tensor]] = [None] * layer_num
        self.used_length_per_layer = [0 for i in range(0, layer_num)]
        self.max_s_list = [0] * layer_num
        self.init_args = (max_b, h, d)
        self.runtime_expand = runtime_expand
        self.dtype = dtype
    
    def clear(self):
        for i in range(len(self.used_length_per_layer)):
            self.used_length_per_layer[i] = 0

    def __getitem__(self, layer_idx: int) -> Tuple[torch.Tensor, torch.Tensor]:
        if layer_idx < len(self.key_cache):
            used = self.used_length_per_layer[layer_idx]
            if self.key_cache[layer_idx] is None:
                return None, None
            return (self.key_cache[layer_idx][:, :used, :, :], 
                    self.value_cache[layer_idx][:, :used, :, :])
        raise IndexError(f"Layer index {layer_idx} out of range")

    def get_seq_length(self, layer_idx: Optional[int] = 0) -> int:
        return self.used_length_per_layer[layer_idx]

    def update(
        self,
        key_states: torch.Tensor,
        value_states: torch.Tensor,
        layer_idx: int,
        cache_kwargs: Optional[Dict[str, Any]] = None,
    ) -> Tuple[torch.Tensor, torch.Tensor]:
        
            
        
        keep_indices = cache_kwargs.get('keep_indices', None) if cache_kwargs else None 
        used_length = self.used_length_per_layer[layer_idx]
        
        
        num_to_copy = keep_indices.shape[-1] if keep_indices is not None else key_states.shape[1]

        
        current_device = key_states.device
        if self.key_cache[layer_idx] is None:
            capacity = num_to_copy + 512
            self.key_cache[layer_idx] = torch.zeros(self.init_args[0], capacity, self.init_args[1], self.init_args[2], device=current_device, dtype=self.dtype)
            self.value_cache[layer_idx] = torch.zeros(self.init_args[0], capacity, self.init_args[1], self.init_args[2], device=current_device, dtype=self.dtype)
            self.max_s_list[layer_idx] = capacity
        
        
        if used_length + num_to_copy > self.max_s_list[layer_idx]:
            if self.runtime_expand:
                
                new_tensor_size = used_length + num_to_copy + 512
                key_cache = self.key_cache[layer_idx]
                value_cache = self.value_cache[layer_idx]
                new_tensor = torch.empty(self.init_args[0], new_tensor_size, self.init_args[1], self.init_args[2], dtype=key_cache.dtype, device=current_device)
                new_tensor[:, :used_length, :, :].copy_(key_cache[:, :used_length, :, :])
                del key_cache
                torch.cuda.empty_cache()
                self.key_cache[layer_idx] = new_tensor
                new_tensor = torch.empty(self.init_args[0], new_tensor_size, self.init_args[1], self.init_args[2], dtype=value_cache.dtype, device=current_device)
                new_tensor[:, :used_length, :, :].copy_(value_cache[:, :used_length, :, :])
                del value_cache
                torch.cuda.empty_cache()
                self.value_cache[layer_idx] = new_tensor
                self.max_s_list[layer_idx] = new_tensor_size
            else:
                raise RuntimeError(f"Layer {layer_idx} cache capacity exceeded!, capacity: {self.max_s_list[layer_idx]}, expected: {used_length + num_to_copy}")

        if keep_indices is None:
            
            keep_indices = torch.arange(num_to_copy, device=current_device)
            triton_copy_4d(key_states, self.key_cache[layer_idx], keep_indices, used_length)
            triton_copy_4d(value_states, self.value_cache[layer_idx], keep_indices, used_length)
        else:
            triton_copy_4d_head_special(key_states, self.key_cache[layer_idx], keep_indices, used_length)
            triton_copy_4d_head_special(value_states, self.value_cache[layer_idx], keep_indices, used_length)

        
        self.used_length_per_layer[layer_idx] += num_to_copy
        new_used = self.used_length_per_layer[layer_idx]
        
        return (self.key_cache[layer_idx][:, :new_used, :, :], 
                self.value_cache[layer_idx][:, :new_used, :, :])
    

class LlamaRMSNorm(nn.Module):
    def __init__(self, hidden_size, eps=1e-6):
        """
        LlamaRMSNorm is equivalent to T5LayerNorm
        """
        super().__init__()
        self.weight = nn.Parameter(torch.ones(hidden_size))
        self.variance_epsilon = eps

    def forward(self, hidden_states):
        input_dtype = hidden_states.dtype
        hidden_states = hidden_states.to(torch.float32)
        variance = hidden_states.pow(2).mean(-1, keepdim=True)
        hidden_states = hidden_states * torch.rsqrt(variance + self.variance_epsilon)
        return self.weight * hidden_states.to(input_dtype)

    def extra_repr(self):
        return f"{tuple(self.weight.shape)}, eps={self.variance_epsilon}"


